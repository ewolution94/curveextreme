export function t(text: string, vars?: Record<string, string | number>) {
  let out = prefs.lang === 'de' ? (DE[text] ?? text) : text;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}
